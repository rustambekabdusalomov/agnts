package perfreview

import (
	"path"
	"strings"

	"agnts/internal/domain"
)

// lockFiles are dependency lock files, by base name.
var lockFiles = map[string]bool{
	"package-lock.json": true, "yarn.lock": true, "pnpm-lock.yaml": true, "go.sum": true, "Cargo.lock": true, "Gemfile.lock": true,
	"poetry.lock": true, "composer.lock": true, "Pipfile.lock": true, "pubspec.lock": true, "bun.lockb": true, "uv.lock": true,
	"packages.lock.json": true, "flake.lock": true, "mix.lock": true, "Podfile.lock": true,
}

// vendored are path parts of code the team did not write.
var vendored = []string{"vendor/", "node_modules/", "third_party/", "third-party/", ".yarn/"}

// Noise reports why a changed file is not the team's work, or "".
func Noise(f domain.FileChange) string {
	p := f.Path
	base := path.Base(p)
	switch {
	case lockFiles[base] || strings.HasSuffix(base, ".lock"):
		return "lock file"
	case strings.HasSuffix(base, ".pb.go") || strings.Contains(base, ".gen.") || strings.HasSuffix(base, "_gen.go") ||
		strings.HasSuffix(base, ".generated.ts") || strings.Contains(p, "/generated/") || strings.HasPrefix(p, "generated/") ||
		strings.HasSuffix(base, ".g.dart") || strings.HasSuffix(base, ".freezed.dart") || generatedMarker(f.Diff):
		return "generated"
	case strings.HasSuffix(base, ".min.js") || strings.HasSuffix(base, ".min.css") || strings.HasSuffix(base, ".map"):
		return "generated"
	case strings.Contains(p, "__snapshots__/") || strings.HasSuffix(base, ".snap"):
		return "snapshot"
	case f.Add == 0 && f.Del == 0:
		return "rename or binary"
	}
	for _, v := range vendored {
		if strings.HasPrefix(p, v) || strings.Contains(p, "/"+v) {
			return "vendored"
		}
	}
	return ""
}

// generatedMarker reports whether an added line says the file is
// generated, as Go and many generators write it.
func generatedMarker(diff string) bool {
	for line := range strings.Lines(diff) {
		if !strings.HasPrefix(line, "+") {
			continue
		}
		l := strings.TrimSpace(strings.TrimPrefix(line, "+"))
		if strings.HasPrefix(l, "// Code generated") || strings.HasPrefix(l, "# Code generated") || strings.Contains(l, "@generated") ||
			strings.HasPrefix(l, "// <auto-generated") {
			return true
		}
	}
	return false
}

// Filter drops noise from a diff and says what it dropped.
func Filter(files []domain.FileChange) (kept []domain.FileChange, dropped []string) {
	for _, f := range files {
		if why := Noise(f); why != "" {
			dropped = append(dropped, f.Path+" ("+why+")")
			continue
		}
		kept = append(kept, f)
	}
	return kept, dropped
}
