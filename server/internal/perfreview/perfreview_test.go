func ptr[T any](v T) *T { return &v }

var t0 = time.Date(2026, 10, 5, 10, 0, 0, 0, time.UTC)

func link(sha string, at time.Time, opts ...func(*domain.CommitLink)) domain.CommitLink {
	l := domain.CommitLink{RepoID: 1, SHA: sha, Subject: "work " + sha, Author: "Alice", AuthorLogin: "alice", AuthorEmail: "alice@x.io",
		CommittedAt: at, OnDefaultAt: ptr(at.Add(time.Hour)), Parents: []string{"p"}}
	for _, o := range opts {
		o(&l)
	}
	return l
}

func TestCleanSquashMergeRebaseRevert(t *testing.T) {
	squash := link("sq", t0, func(l *domain.CommitLink) {
		l.MergeKind, l.PRNumber, l.Author, l.AuthorLogin, l.AuthorEmail = domain.MergeKindSquash, ptr(7), "Merger", "merger", "m@x.io"
	})
	oneSquash := link("sq1", t0, func(l *domain.CommitLink) { l.MergeKind, l.PRNumber = domain.MergeKindSquash, ptr(8) })
	merge := link("mg", t0, func(l *domain.CommitLink) { l.MergeKind, l.Parents = domain.MergeKindMerge, []string{"a", "b"} })
	branch := link("b1", t0)
	rebased := link("b1copy", t0) // a rebase merge's copy: same author, date and subject
	rebased.Subject = branch.Subject
	revert := link("rv", t0, func(l *domain.CommitLink) { l.Subject, l.Reverts = `Revert "work b1"`, "b1" })
	pr := map[PullKey][]domain.PushedCommit{
		{1, 7}: {
			{SHA: "P1", Message: "wip", Author: "Bob", AuthorLogin: "bob", AuthorEmail: "bob@x.io", Date: t0},
			{SHA: "P2", Message: "more", Author: "Carol", AuthorLogin: "carol", AuthorEmail: "c@x.io", Date: t0.Add(24 * time.Hour)},
		},
	}
	c := Clean([]domain.CommitLink{squash, oneSquash, merge, branch, rebased, revert}, pr, func(_ int64, sha string) bool { return sha == "p2" })
	if len(c.Reverts) != 1 || len(c.Commits) != 5 {
		t.Fatalf("commits %d reverts %d", len(c.Commits), len(c.Reverts))
	}
	got := map[string]Earner{}
	for _, e := range c.Earners {
		got[e.SHA] = e
	}
	// The squash's own commits earn, not the merger; a one-commit squash
	// with no stored commits falls back to its author; the merge earns
	// nothing; the rebase copy is collapsed.
	if _, ok := got["sq"]; ok {
		t.Fatal("the squash commit earned")
	}
	if got["p1"].Login != "bob" || !got["p2"].Agent || got["sq1"].Login != "alice" || len(c.Earners) != 4 {
		t.Fatalf("earners: %+v", c.Earners)
	}
	if _, ok := got["mg"]; ok {
		t.Fatal("a merge commit earned")
	}
	plan := c.Repos[1]
	if plan.Source() != SourcePullRequest || len(plan.Pulls) != 2 || len(plan.Squashes) != 2 || len(plan.Commits) != 2 {
		t.Fatalf("plan: %+v", plan)
	}
}

