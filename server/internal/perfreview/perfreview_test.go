func near(a, b float64) bool { return math.Abs(a-b) < 1e-9 }

func TestFactsScoreAndClamp(t *testing.T) {
	small := Facts{ChangedLines: 40}
	risky := Facts{ChangedLines: 40, RiskyAreas: []string{RiskConcurrency}}
	big := Facts{ChangedLines: 1500}
	cases := []struct {
		name        string
		f           Facts
		model       int
		want        int
		wantClamped bool
	}{
		{"a large diff scored low stays low", big, 1, 1, false},
		{"a small risky diff can reach 8", risky, 8, 8, false},
		{"a small risky diff cannot reach 13", risky, 13, 8, true},
		{"a small plain diff is clamped one step up", small, 8, 2, true},
		{"off the scale goes to the step below", small, 4, 2, true},
		{"zero means 1", small, 0, 1, false},
	}
	for _, c := range cases {
		got, clamped := Clamp(c.model, c.f)
		if got != c.want || clamped != c.wantClamped {
			t.Errorf("%s: got %d clamped=%v", c.name, got, clamped)
		}
	}
	if FactsScore(risky) != 2 || FactsScore(Facts{ChangedLines: 9000, RiskyAreas: []string{"x"}, Repositories: 3}) != 13 ||
		FactsScore(Facts{ChangedLines: 300, Repositories: 3}) != 5 {
		t.Fatal("facts score")
	}
}

